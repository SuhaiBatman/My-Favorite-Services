#!/usr/bin/env node
/**
 * Syncs constants/supabaseEnv.ts from the active profile (APP_ENV).
 */
const fs = require('fs');
const path = require('path');
const { resolveSupabaseEnv, resolveProfile } = require('./load-project-env.cjs');

const root = path.join(__dirname, '..');
const outFile = path.join(root, 'constants', 'supabaseEnv.ts');
const defaultsFile = path.join(root, 'constants', 'supabaseEnv.defaults.ts');

function syncSupabaseEnv({ profile = process.env.APP_ENV, quiet = false } = {}) {
  const resolved = resolveProfile(profile);
  const env = resolveSupabaseEnv(resolved);

  if (!fs.existsSync(outFile) && fs.existsSync(defaultsFile)) {
    fs.copyFileSync(defaultsFile, outFile);
  }

  const contents = `// Auto-generated by scripts/write-supabase-env.cjs — do not edit
// Profile: ${resolved} (APP_ENV=${resolved})
export const SUPABASE_URL = ${JSON.stringify(env.EXPO_PUBLIC_SUPABASE_URL ?? '')};
export const SUPABASE_ANON_KEY = ${JSON.stringify(env.EXPO_PUBLIC_SUPABASE_KEY ?? '')};
export const SUPABASE_USE_LOCAL = ${JSON.stringify(env.EXPO_PUBLIC_SUPABASE_USE_LOCAL ?? '')};
`;

  const previous = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  const changed = previous !== contents;
  if (changed) {
    fs.writeFileSync(outFile, contents, 'utf8');
    if (!quiet) {
      const key = env.EXPO_PUBLIC_SUPABASE_KEY ?? '';
      const keyKind = key.startsWith('sb_publishable_')
        ? 'publishable'
        : key.startsWith('eyJ')
          ? 'jwt'
          : 'unset';
      console.log(
        `[supabase-env:${resolved}] ${env.EXPO_PUBLIC_SUPABASE_URL || '(no url)'} | key: ${keyKind}`
      );
    }
  }

  return env;
}

if (require.main === module) {
  const profile =
    process.argv[2] ||
    process.env.APP_ENV ||
    process.env.EAS_BUILD_PROFILE ||
    'local';
  process.env.APP_ENV = resolveProfile(profile);
  syncSupabaseEnv({ profile: process.env.APP_ENV });
}

module.exports = { syncSupabaseEnv };
